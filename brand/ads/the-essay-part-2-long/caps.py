import json
ws = json.load(open('wt.json'))
def M(i): return i if i < 92 else i + 19 if i <= 135 else i + 38 if i <= 154 else i + 54
G = [(0,3),(4,6),(7,9),(10,13),(14,16),(17,19),(20,22),(23,26),(27,29),(30,31),(32,34),(35,37),(38,40),(41,44),(45,48),(49,49),(50,51),(52,53),
(54,56),(57,58),(59,61),(62,63),(64,66),(67,69),(70,73),(74,77),(78,80),(81,82),(83,86),(87,88),(89,91),(92,94),(95,97),(98,100),(101,103),
(104,106),(107,109),(110,111),(112,114),(115,117),(118,120),(121,123),(124,125),(126,127),(128,130),(131,132),(133,135),(136,138),(139,140),
(141,143),(144,145),(146,147),(148,150),(151,154),(155,156),(157,159),(160,160),(161,162),(163,166),(167,167),(168,169),(170,172),(173,176),
(177,179),(180,182),(183,185),(186,187),(188,188),(189,190),(191,193),(194,195),(196,197),(198,199),(200,202),(203,206),(207,209),(210,211),
(212,215),(216,217),(218,219),(220,223),(224,227),(228,230),(231,234),(235,238),(239,243)]
Q = set(); [Q.update(range(a, b + 1)) for a, b in [(4,6),(32,40),(74,91),(161,166),(177,193),(198,199)]]
COL = {}
for i in [17,31,48,49,53,91,114,187,193,215,219,227,234]: COL[i] = "#ff3b3b"
for i in [80,81,82,102,103,60,61,124,125,126,127,155,156,167,194,195]: COL[i] = "#ffd23f"
for i in [140,146,147,210,211,237,238]: COL[i] = "#3df07a"
for i in [15,16,94,200]: COL[i] = "#5fb8ff"
G = [(M(a), M(b)) for a, b in G] + [(92,93),(94,95),(96,98),(99,99),(100,100),(101,103),(104,106),(107,110),(155,158),(159,160),(161,162),(163,164),(165,168),(169,171),(172,173),(193,195),(196,198),(199,202),(203,205),(206,208)]
G.sort()
COL = {M(k): v for k, v in COL.items()}
for i in [99,100,164,197]: COL[i] = '#ff3b3b'
for i in [195,204,205,206,207,208]: COL[i] = '#3df07a'
Q = {M(i) for i in Q}
caps = []
for a, b in G:
    parts = []
    for i in range(a, b + 1):
        t = ws[i]["w"].upper().replace('"', "")
        if i == 160: t = "JAKE:"
        if i == 197: t = "HART:"
        c = COL.get(i) or ("#ff7ac8" if i in Q else None)
        parts.append(f'<b style="color:{c}">{t}</b>' if c else t)
    h = " ".join(parts)
    if a in Q and (a - 1) not in Q: h = "“" + h
    if b in Q and (b + 1) not in Q: h = h + "”"
    caps.append([ws[a]["s"], h])
open('web/caps.js', 'w').write("const CAPS = " + json.dumps(caps, ensure_ascii=False) + ";\n"); print(len(caps))
